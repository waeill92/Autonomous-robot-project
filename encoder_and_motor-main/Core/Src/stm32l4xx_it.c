/**
  * @brief This function handles System tick timer.
  */


/* USER CODE BEGIN PV */
// Global variables for odometry
volatile float distance1 = 0.0f;
volatile float distance2 = 0.0f;

// Variables to store the last known tick count
int32_t prev_ticks1 = 0;
int32_t prev_ticks2 = 0;
/* USER CODE END PV */

void SysTick_Handler(void)
{
  /* USER CODE BEGIN SysTick_IRQn 0 */
	indx++;
	if (indx == 100){
		speed1 = (((ticks1 - oldpos1)*10)/224.0)*60; // speeds in clicks/sec
		oldpos1 = ticks1;
		speed2 = (((ticks2 - oldpos2)*10)/224.0)*60;
		oldpos2 = ticks2;

		// Calculate the change in ticks since the last update
		// This handles the 16-bit timer wrapping around (e.g., from 65535 to 0)
		int16_t delta_ticks1 = ticks1 - (int16_t)prev_ticks1;

		// Calculate the distance traveled in this interval and add to total
		distance1 += (float)delta_ticks1 * DISTANCE_PER_TICK_CM;

		// Store the current tick count for the next calculation
		prev_ticks1 = ticks1;


		// --- Motor 2 (TIM5) ---
		// Repeat the same logic for the second motor
		int16_t delta_ticks2 = ticks2 - (int16_t)prev_ticks2;
		distance2 += (float)delta_ticks2 * DISTANCE_PER_TICK_CM;
		prev_ticks2 = ticks2;

		indx=0;
	}
  /* USER CODE END SysTick_IRQn 0 */
  HAL_IncTick();
  /* USER CODE BEGIN SysTick_IRQn 1 */

  /* USER CODE END SysTick_IRQn 1 */
}





